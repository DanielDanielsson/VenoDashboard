import { readdirSync, writeFileSync, existsSync, readFileSync } from 'fs';
import { join, posix } from 'path';

const ROOT = join(import.meta.dirname, '..');
const UI_DIR = join(ROOT, 'ui');
const OUTPUT = join(ROOT, 'src', 'styles', '_component-imports.css');

const dirs = ['components', 'compositions'];
const imports = [];

for (const dir of dirs) {
  const fullDir = join(UI_DIR, dir);
  if (!existsSync(fullDir)) continue;

  const files = readdirSync(fullDir, { recursive: true })
    .filter((f) => typeof f === 'string' && f.endsWith('.css'))
    .sort();

  for (const file of files) {
    const relPath = posix.join('../../ui', dir, file.split('\\').join('/'));
    imports.push(`@import "${relPath}";`);
  }
}

const content = [
  '/* Auto-generated by scripts/generate-component-imports.mjs */',
  '/* Do not edit manually — re-run: node scripts/generate-component-imports.mjs */',
  '',
  ...imports,
  '',
].join('\n');

if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== content) {
  writeFileSync(OUTPUT, content);
  console.log(`Generated ${imports.length} component CSS import(s)`);
} else {
  console.log('Component CSS imports unchanged');
}
